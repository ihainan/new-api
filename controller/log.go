// GetPortalMetrics 为员工门户概览页提供聚合数据。
//
// 与 GetLogsSelfStat 的区别：那个按 username 聚合（用户名可变，改名后对不上），
// 且只有 quota/rpm/tpm。这里一律按 user_id，并额外给出缓存占比、首字延迟、
// 失败比例与折线/模型分布。
func GetPortalMetrics(c *gin.Context) {
	userId := c.GetInt("id")

	end := time.Now().Unix()
	start := end - 24*3600
	if v, err := strconv.ParseInt(c.Query("start_timestamp"), 10, 64); err == nil && v > 0 {
		start = v
	}
	if v, err := strconv.ParseInt(c.Query("end_timestamp"), 10, 64); err == nil && v > 0 {
		end = v
	}
	/*
	 * 时间戳来自请求参数，必须先夹到合理范围再往下算：不夹的话传一个接近
	 * int64 上限的值，后面按粒度累加就会溢出（2026-09-21 评审发现，一个请求
	 * 就能把进程拖死）。未来的数据不存在，结束时间最多到此刻；开始不能为负。
	 */
	now := time.Now().Unix()
	if end > now {
		end = now
	}
	if start < 0 {
		start = 0
	}
	if end <= start {
		common.ApiErrorMsg(c, "invalid time range")
		return
	}
	// 上限一年：再长的区间对个人看板没有意义，而且会把明细扫描拉到不可接受的量级。
	if end-start > 366*24*3600 {
		common.ApiErrorMsg(c, "time range too large")
		return
	}

	// 粒度由区间长度决定，目标是 24~60 个点。让后端决定可以避免前端为
	// 「30 天按小时」这种组合算出上千个点。
	span := end - start
	bucket := int64(3600)
	switch {
	case span <= 2*3600:
		bucket = 300
	case span <= 12*3600:
		bucket = 900
	case span <= 2*24*3600:
		bucket = 3600
	case span <= 10*24*3600:
		bucket = 6 * 3600
	default:
		bucket = 24 * 3600
	}

	metrics, err := model.GetPortalMetrics(userId, start, end, bucket, constant.ErrorLogEnabled)
	if err != nil {
		common.ApiError(c, err)
		return
	}
	common.ApiSuccess(c, metrics)
}
